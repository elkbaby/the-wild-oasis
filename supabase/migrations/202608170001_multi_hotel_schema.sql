create extension if not exists btree_gist;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'hotel_role') then
    create type public.hotel_role as enum (
      'owner',
      'manager',
      'front_desk',
      'finance'
    );
  end if;
end
$$;

create table if not exists public.hotels (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  location text not null default '',
  timezone text not null default 'UTC',
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  "fullName" text,
  email text,
  avatar text default '',
  created_at timestamptz not null default now()
);

create table if not exists public.hotel_members (
  id bigint generated by default as identity primary key,
  "hotelId" bigint not null references public.hotels(id) on delete cascade,
  "userId" uuid not null references public.profiles(id) on delete cascade,
  role public.hotel_role not null default 'front_desk',
  created_at timestamptz not null default now(),
  unique ("hotelId", "userId")
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, "fullName", email, avatar)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'fullName', ''),
    new.email,
    coalesce(new.raw_user_meta_data ->> 'avatar', '')
  )
  on conflict (id) do update
  set email = excluded.email,
      "fullName" = coalesce(nullif(excluded."fullName", ''), profiles."fullName");
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert or update of email, raw_user_meta_data on auth.users
  for each row execute function public.handle_new_user();

insert into public.profiles (id, "fullName", email, avatar)
select
  id,
  coalesce(raw_user_meta_data ->> 'fullName', ''),
  email,
  coalesce(raw_user_meta_data ->> 'avatar', '')
from auth.users
on conflict (id) do update
set email = excluded.email,
    "fullName" = coalesce(nullif(excluded."fullName", ''), profiles."fullName");

