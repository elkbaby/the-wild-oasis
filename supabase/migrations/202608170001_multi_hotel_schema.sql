create table if not exists public.maintenance_blocks (
  id bigint generated by default as identity primary key,
  "hotelId" bigint not null references public.hotels(id) on delete cascade,
  "cabinId" bigint not null references public.cabins(id) on delete cascade,
  "startDate" date not null,
  "endDate" date not null,
  reason text not null,
  "createdBy" uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  constraint maintenance_dates_valid check ("endDate" > "startDate")
);

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'bookings_cabin_same_hotel_fkey'
  ) then
    alter table public.bookings
      add constraint bookings_cabin_same_hotel_fkey
      foreign key ("cabinId", "hotelId")
      references public.cabins(id, "hotelId") on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint where conname = 'bookings_guest_same_hotel_fkey'
  ) then
    alter table public.bookings
      add constraint bookings_guest_same_hotel_fkey
      foreign key ("guestId", "hotelId")
      references public.guests(id, "hotelId") on delete restrict;
  end if;

  if not exists (
    select 1 from pg_constraint where conname = 'maintenance_cabin_same_hotel_fkey'
  ) then
    alter table public.maintenance_blocks
      add constraint maintenance_cabin_same_hotel_fkey
      foreign key ("cabinId", "hotelId")
      references public.cabins(id, "hotelId") on delete cascade;
  end if;
end
$$;

create index if not exists maintenance_hotel_dates_idx
  on public.maintenance_blocks ("hotelId", "startDate", "endDate");

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'maintenance_no_overlap'
  ) then
    alter table public.maintenance_blocks
      add constraint maintenance_no_overlap
      exclude using gist (
        "hotelId" with =,
        "cabinId" with =,
        daterange("startDate", "endDate", '[)') with &&
      );
  end if;
end
$$;

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  "hotelId" bigint not null references public.hotels(id) on delete cascade,
  "actorId" uuid references public.profiles(id) on delete set null,
  action text not null check (action in ('INSERT', 'UPDATE', 'DELETE')),
  "resourceType" text not null,
  "resourceId" text not null,
  "beforeData" jsonb,
  "afterData" jsonb,
  created_at timestamptz not null default now()
);

create index if not exists audit_logs_hotel_created_idx
  on public.audit_logs ("hotelId", created_at desc);
