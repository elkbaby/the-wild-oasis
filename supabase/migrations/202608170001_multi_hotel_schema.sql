alter table public.cabins add column if not exists "hotelId" bigint;
alter table public.bookings add column if not exists "hotelId" bigint;
alter table public.guests add column if not exists "hotelId" bigint;
alter table public.settings add column if not exists "hotelId" bigint;

do $$
declare
  default_hotel_id bigint;
begin
  select id into default_hotel_id
  from public.hotels
  where slug = 'the-wild-oasis';

  update public.cabins set "hotelId" = default_hotel_id where "hotelId" is null;
  update public.bookings set "hotelId" = default_hotel_id where "hotelId" is null;
  update public.guests set "hotelId" = default_hotel_id where "hotelId" is null;
  update public.settings set "hotelId" = default_hotel_id where "hotelId" is null;

  insert into public.hotel_members ("hotelId", "userId", role)
  select default_hotel_id, id, 'owner'::public.hotel_role
  from public.profiles
  on conflict ("hotelId", "userId") do nothing;
end
$$;

alter table public.cabins alter column "hotelId" set not null;
alter table public.bookings alter column "hotelId" set not null;
alter table public.guests alter column "hotelId" set not null;
alter table public.settings alter column "hotelId" set not null;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'cabins_hotel_id_fkey') then
    alter table public.cabins
      add constraint cabins_hotel_id_fkey
      foreign key ("hotelId") references public.hotels(id) on delete restrict;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'bookings_hotel_id_fkey') then
    alter table public.bookings
      add constraint bookings_hotel_id_fkey
      foreign key ("hotelId") references public.hotels(id) on delete restrict;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'guests_hotel_id_fkey') then
    alter table public.guests
      add constraint guests_hotel_id_fkey
      foreign key ("hotelId") references public.hotels(id) on delete restrict;
  end if;

  if not exists (select 1 from pg_constraint where conname = 'settings_hotel_id_fkey') then
    alter table public.settings
      add constraint settings_hotel_id_fkey
      foreign key ("hotelId") references public.hotels(id) on delete cascade;
  end if;
end
$$;

